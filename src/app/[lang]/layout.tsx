import type { Metadata, Viewport } from "next";
import { notFound } from "next/navigation";
import "../globals.css";
import { i18n, isLocale, type Locale } from "@/i18n/config";
import { getDictionary } from "@/i18n/get-dictionary";
import { I18nProvider } from "@/i18n/i18n-provider";
import { iranSans, sfPro } from "@/config/fonts";
import { profile } from "@/data/profile";
import { ThemeProvider } from "@/components/providers/theme-provider";
import {
  SITE_URL,
  languageAlternates,
  ogLocale,
  personJsonLd,
  serializeJsonLd,
} from "@/lib/seo";
import { THEME_INIT } from "@/lib/theme-init";
import { cn } from "@/lib/utils";

type Props = {
  children: React.ReactNode;
  params: Promise<{ lang: string }>;
};

/** Narrow the URL segment to a supported locale or 404. */
async function resolveLocale(params: Props["params"]): Promise<Locale> {
  const { lang } = await params;
  if (!isLocale(lang)) notFound();
  return lang;
}

export async function generateStaticParams() {
  return i18n.locales.map((lang) => ({ lang }));
}

export async function generateMetadata({
  params,
}: Pick<Props, "params">): Promise<Metadata> {
  const lang = await resolveLocale(params);
  const dict = await getDictionary(lang);

  return {
    metadataBase: new URL(SITE_URL),
    title: dict.meta.title,
    description: dict.meta.description,
    keywords: dict.meta.keywords,
    applicationName: dict.menu.os,
    authors: [{ name: dict.profile.name, url: profile.social.github }],
    creator: dict.profile.name,
    publisher: dict.profile.name,
    category: "technology",
    alternates: {
      canonical: `/${lang}`,
      languages: languageAlternates(),
    },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        "max-image-preview": "large",
        "max-snippet": -1,
    },
    },
    openGraph: {
      type: "profile",
      siteName: dict.profile.name,
      title: dict.meta.title,
      description: dict.meta.description,
      url: `${SITE_URL}/${lang}`,
      locale: ogLocale(lang),
      alternateLocale: i18n.locales
        .filter((locale) => locale !== lang)
        .map(ogLocale),
      firstName: profile.firstName,
      lastName: profile.lastName,
      username: "matinmza",
    },
    twitter: {
      card: "summary_large_image",
      title: dict.meta.title,
      description: dict.meta.description,
    },
    icons: {
      icon: [
        { url: "/favicon.ico", sizes: "any" },
        { url: "/icon.svg", type: "image/svg+xml" },
      ],
      // Route generated by src/app/apple-icon.tsx — extensionless by design.
      apple: [{ url: "/apple-icon", sizes: "180x180", type: "image/png" }],
    },
    manifest: "/manifest.webmanifest",
  };
}

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#dfe3ea" },
    { media: "(prefers-color-scheme: dark)", color: "#0a0b10" },
  ],
};

export default async function RootLayout({ children, params }: Props) {
  const lang = await resolveLocale(params);
  const dict = await getDictionary(lang);

  return (
    <html
      lang={lang}
      dir={lang === "fa" ? "rtl" : "ltr"}
      suppressHydrationWarning
    >
      <body
        className={cn(
          sfPro.variable,
          iranSans.variable,
          "scrollbar-ios antialiased",
          lang === "fa" ? "font-iran-sans" : "font-sf-pro"
        )}
      >
        {/* Inline and blocking on purpose: the theme follows the clock, which
            CSS cannot read, so the rule has to run before the first paint. */}
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT }} />
        {/* Structured data — rendered on the server only, never re-executed. */}
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{
            __html: serializeJsonLd(personJsonLd(dict, lang)),
          }}
        />
        <ThemeProvider>
          <I18nProvider dict={dict} lang={lang}>
            {children}
          </I18nProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
